<?php
/**
 * Порядок статей внутри рубрик BetterDocs — по релевантности, а не по новизне.
 *
 * Зачем: порядок хранится мета-полем термина `_docs_order` (список id через
 * запятую, Core/Query.php::get_docs_order_by_terms). Статьи, которых в списке
 * НЕТ, плагин ставит в НАЧАЛО рубрики — поэтому 12 статей, добавленных
 * 2026-09-01, вылезли поверх вводных. `menu_order` записи на витрину не
 * влияет, пока мета существует, а она есть у всех 11 рубрик.
 *
 * Запуск на сервере (wp-cli на этой машине НЕТ):
 *   php /tmp/betterdocs-order.php          — показать, что изменится
 *   php /tmp/betterdocs-order.php --apply  — записать
 *
 * Скрипт идемпотентный и проверяет себя: если список для рубрики не совпадает
 * с реальным составом статей (кто-то добавил или удалил статью), рубрика
 * пропускается с сообщением, а не переписывается вслепую.
 */

require_once "/var/www/md33/data/www/rentos365.app/wp-load.php";

$apply = in_array("--apply", $argv, true);

// Порядок собран по маршруту читателя: сначала то, что делают первым.
// Новые статьи 2026-09-01: 2331 печать, 2332 слепой ввод, 2333 техподдержка,
// 2334 импорт клиентов, 2335 разбить оплату, 2336 подписка, 2337 бот клиента,
// 2338 разница, 2339 возвраты/тесты, 2340 устройства, 2341 сотрудник-старт,
// 2342 /kassa.
$orders = [
    // Начало работы: регистрация → СЛОВАРЬ (2345) вторым, потому что без него
    // остальные статьи нечитаемы: «зона», «актив», «сдача итогов» нигде больше
    // не объясняются → точка → устройство → сотрудник → его маршрут →
    // переключение входов → PWA → эксплуатация → деньги компании → и в конце
    // справочные «что делать, если не работает» (2346) и «как написать в
    // поддержку» (2347): их читают не по порядку, а когда прижало.
    6 => [326, 2345, 327, 2296, 328, 329, 432, 485, 2341, 459, 462, 2340, 457, 458, 2336, 431, 2346, 2347],

    // Режимы учёта: настройка зоны и тарифов по режимам → правка сущностей →
    // исправление сдачи → затем всё «Сотрудник:».
    16 => [330, 331, 333, 332, 334, 351, 495, 464, 463, 335, 352, 480, 2339, 481, 482, 483, 484],

    // Деньги: сначала «Разница» — без неё остальное не читается, затем
    // движение денег, расходы, разбивка оплаты и отчёт.
    17 => [2338, 336, 552, 337, 338, 497, 496, 2335, 339],

    // Товары и Абонементы: создание → продажа сотрудником → владельческое.
    21 => [353, 487, 354, 2337, 355, 2334, 356, 544],

    // Настройки: сначала общие настройки и вид, потом печать, потом весь
    // Telegram одним блоком, потом контроль, и удаление данных — последним.
    26 => [427, 429, 426, 2331, 419, 420, 421, 422, 2342, 423, 425, 424, 2332, 2333, 428],
];

$changed = 0;
foreach ($orders as $termId => $wanted) {
    $term = get_term($termId, "doc_category");
    if (!$term || is_wp_error($term)) {
        echo "term {$termId}: НЕ НАЙДЕН, пропуск\n";
        continue;
    }

    // Реальный состав рубрики — источник истины для проверки.
    $actual = get_posts([
        "post_type"      => "docs",
        "post_status"    => "publish",
        "posts_per_page" => -1,
        "fields"         => "ids",
        "tax_query"      => [[
            "taxonomy" => "doc_category",
            "field"    => "term_id",
            "terms"    => $termId,
        ]],
    ]);

    sort($actual);
    $check = $wanted;
    sort($check);

    if ($actual !== $check) {
        $missing = array_diff($actual, $wanted);
        $extra   = array_diff($wanted, $actual);
        echo "term {$termId} ({$term->name}): СОСТАВ РАЗОШЁЛСЯ, пропуск\n";
        if ($missing) echo "  нет в списке: " . implode(",", $missing) . "\n";
        if ($extra)   echo "  лишние в списке: " . implode(",", $extra) . "\n";
        continue;
    }

    $current = (string) get_term_meta($termId, "_docs_order", true);
    $next    = implode(",", $wanted);

    if ($current === $next) {
        echo "term {$termId} ({$term->name}): уже так, пропуск\n";
        continue;
    }

    echo "term {$termId} ({$term->name}):\n  было: {$current}\n  станет: {$next}\n";
    if ($apply) {
        update_term_meta($termId, "_docs_order", $next);
        $changed++;
    }
}

if ($apply) {
    echo "\nЗаписано рубрик: {$changed}\n";
    // Витрина /docs/ и страницы рубрик лежат в кэше WP Rocket.
    if (function_exists("rocket_clean_domain")) {
        rocket_clean_domain();
        echo "Кэш WP Rocket очищен\n";
    }
} else {
    echo "\nПоказан предпросмотр. Запустите с --apply, чтобы записать.\n";
}
