-- Окно у счётчика неверных паролей (аудит 2026-08-13).
--
-- До этого User.failedPasswordAttempts не имел окна: обнулялся только удачным
-- входом, поэтому правило звучало не «5 неверных подряд», а «5 неверных за всё
-- время с последнего входа». У владельца, заходящего раз в неделю, промахи
-- копились месяцами — та же ошибка, что 2026-08-08 разобрали у ПИН-кода.
--
-- Существующие счётчики обнуляем: они накоплены по старому правилу, без окна,
-- и переносить их в новую логику бессмысленно — это ровно те «застарелые
-- промахи», от которых окно и защищает. Снимаем и активные блокировки: они
-- поставлены прежним порогом в 5 попыток, который как раз и позволял запереть
-- владельца снаружи, зная только его email.
ALTER TABLE "User" ADD COLUMN "failedPasswordFirstAt" TIMESTAMP(3);

UPDATE "User"
SET "failedPasswordAttempts" = 0,
    "passwordLockedUntil" = NULL
WHERE "failedPasswordAttempts" > 0 OR "passwordLockedUntil" IS NOT NULL;
