import { prisma } from "@/lib/prisma";
import type { SessionTokenDetails } from "@/lib/session-crypto";

// Отзыв всех ранее выданных сессий пользователя (аудит 2026-08-13).
//
// Подпись сессионного токена зависит только от userId, поэтому «выпустить
// новый токен» никогда не обесценивало старый: смена или сброс пароля выдавали
// свежую куку, а уже перехваченное значение продолжало работать до конца
// своего срока (до недели). То есть самое очевидное действие человека,
// заподозрившего, что его сессию увели — «сменю пароль» — от этой сессии как
// раз и не спасало.
//
// Механика самая дешёвая из возможных: в токен зашито время выдачи
// (signSessionToken), у пользователя лежит отметка sessionsValidFrom, и токен
// старше отметки не принимается. Никакого хранилища живых сессий заводить не
// нужно — состояние остаётся одним полем на пользователе, а проверка
// бесплатна: она делается там, где пользователь и так читается из базы
// (requireOwner/requireSuperAdmin), без дополнительного запроса.
export function isSessionRevoked(
  session: SessionTokenDetails,
  sessionsValidFrom: Date | null
): boolean {
  if (!sessionsValidFrom) return false;
  // Строгое «меньше», без запаса: время выдачи ставит сервер сам в
  // createSession, часы клиента в этом не участвуют, поэтому сдвига,
  // который стоило бы прощать, здесь нет.
  return session.issuedAtMs < sessionsValidFrom.getTime();
}

/**
 * Обесценивает все существующие сессии пользователя. Вызывается там, где
 * меняется пароль (сброс по ссылке из письма и смена из кабинета) — то есть
 * ровно там, где человек рассчитывает, что «чужой вход больше не работает».
 *
 * ВАЖЕН ПОРЯДОК: сначала отзыв, потом createSession. Отметка ставится текущим
 * моментом, а сравнение идёт по строгому «меньше», поэтому сессия, выданная
 * после этого вызова, переживает его — но выданная до, пусть даже
 * миллисекундой раньше, нет. Сброс пароля сразу логинит человека, и если
 * поменять эти два шага местами, он выйдет из системы сам себя.
 */
export async function revokeUserSessions(userId: string): Promise<void> {
  await prisma.user.update({
    where: { id: userId },
    data: { sessionsValidFrom: new Date() },
  });
}
