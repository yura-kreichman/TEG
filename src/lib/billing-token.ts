import { signExpiringToken, verifyExpiringToken } from "@/lib/session-crypto";

/**
 * Токен кабинета в ссылке на оплату (решение пользователя 2026-08-10).
 *
 * ЗАЧЕМ. Единственной связью между платежом в FluentCart и кабинетом в RentOS
 * был email (см. syncTenantFromFluentCartEvent). Владелец, который завёл
 * кабинет на личный адрес, а платит корпоративной картой на адрес бухгалтерии,
 * получал ВТОРОЙ, пустой кабинет с активной подпиской: вебхук не находил
 * тенанта по чужому email и создавал новый (provisionTenantFromPurchase).
 * Настроенный кабинет оставался на Free и со временем попадал под
 * автоудаление брошенных (lib/tenant-lifecycle.ts) — то есть человек платил и
 * терял данные.
 *
 * КАК. Ссылка "Управлять подпиской" уносит на сайт подписанный идентификатор
 * кабинета, сайт кладёт его в мету заказа и возвращает в теле вебхука, вебхук
 * ищет тенанта по нему ПЕРВЫМ. При живом токене адрес плательщика перестаёт
 * что-либо решать.
 *
 * ПОЧЕМУ ПОДПИСАННЫЙ, А НЕ СЫРОЙ id. Сырой id в ссылке — это возможность
 * привязать свою оплату к чужому кабинету, а вместе с ней и свою последующую
 * отмену: событие subscription_eot по чужому заказу перевело бы жертву в
 * expired. Секрет знает только RentOS — сайту он для этой задачи не нужен, он
 * таскает строку как непрозрачную.
 */

// 30 дней: человек нажимает "Управлять подпиской", думает, советуется и
// возвращается к оплате не в тот же вечер. Бессрочный токен здесь плох ровно
// тем, от чего защищает подпись: однажды утёкшая ссылка работала бы вечно.
// Просроченный токен не ломает покупку — вебхук просто откатывается на прежний
// поиск по email, то есть на поведение до этой правки.
export const BILLING_TOKEN_TTL_MS = 30 * 24 * 60 * 60 * 1000;

// Префикс подписываемого значения — разделение назначений. Схема подписи общая
// с сессиями (lib/session-crypto.ts), и без префикса токен оплаты был бы
// синтаксически валидной cookie сессии имперсонации, а сессия — валидным
// токеном оплаты. Префикс делает эти два множества непересекающимися при том
// же секрете.
const BILLING_TOKEN_PREFIX = "billing_";

export function signTenantBillingToken(tenantId: string, now: Date = new Date()): string {
  return signExpiringToken(`${BILLING_TOKEN_PREFIX}${tenantId}`, now.getTime() + BILLING_TOKEN_TTL_MS);
}

/** tenantId или null — подпись не сошлась, срок вышел или это токен не отсюда. */
export function verifyTenantBillingToken(token: string): string | null {
  const value = verifyExpiringToken(token);
  if (!value || !value.startsWith(BILLING_TOKEN_PREFIX)) return null;
  return value.slice(BILLING_TOKEN_PREFIX.length) || null;
}
