import type { MetadataRoute } from "next";

// start_url ВСЕГДА "/" — куда идти дальше, решает сам корень (src/app/(app)/
// page.tsx): валидная сессия Владельца ведёт в кабинет, иначе активированное
// устройство точки уводит на /operator, а без того и другого показывается
// приветственный экран.
//
// Раньше здесь стояло `device ? "/operator/login" : "/"` — попытка закрыть
// прод-баг 2026-07-14 (сотрудник ставил PWA с привязанного телефона, а ярлык
// открывал вход ВЛАДЕЛЬЦА). Причину того бага давно устранила правка корня
// 2026-07-29, а этот динамический адрес породил свой, зеркальный (найден
// владельцем 2026-08-16): человек, который И владелец, И сотрудник, ставил
// приложение с телефона, привязанного к точке, — и ярлык НАВСЕГДА уводил его
// в интерфейс сотрудника. Ни Итогов, ни Остатков он там не видел, а закрытие
// приложения не помогало: start_url фиксируется в момент установки и при
// запуске не пересчитывается.
//
// Статический адрес такой ситуации не создаёт: маршрут выбирается при каждом
// открытии по актуальной сессии, а не по состоянию cookie в день установки.
export default function manifest(): MetadataRoute.Manifest {
  return {
    id: "/",
    name: "RentOS",
    short_name: "RentOS",
    description: "RentOS SaaS",
    start_url: "/",
    // scope задаём явно, хотя start_url снова статический (найдено
    // 2026-08-13, когда адрес был динамическим): без него спецификация
    // выводит область из самого start_url, и любое будущее возвращение к
    // адресу вида "/operator/login" молча вынесло бы весь кабинет владельца
    // за пределы приложения — браузер показывал бы на нём свою адресную
    // строку или уводил в отдельное окно (жалоба «ярлык PWA открывает
    // Chrome»).
    // "/" — приложение это весь ориджин: владелец и сотрудник живут на одном
    // домене и переходят друг к другу (OperatorLoginToggle, OwnerLoginToggle,
    // кнопка «Открыть приложение сотрудника» после привязки).
    scope: "/",
    display: "standalone",
    // display_override — браузер пробует значения по порядку, использует
    // первое поддерживаемое (запрос пользователя 2026-07-22):
    // - window-controls-overlay (Windows/desktop Chromium) — убирает ряд
    //   иконок браузера (пазл-расширения/загрузки/меню "⋮") из шапки
    //   установленного PWA-окна, оставляя только нативные
    //   свернуть/развернуть/закрыть (их подменить кастомными нельзя — это
    //   осознанное ограничение платформы против подделки чужого окна).
    // fullscreen (Android) убран из списка (запрос пользователя 2026-07-24:
    // "не надо делать PWA на Android на весь экран") — без строки состояния
    // не видно времени/заряда/уведомлений, оператору на точке это нужнее,
    // чем лишний вертикальный сантиметр.
    // display (standalone) — обязательный fallback для браузеров без
    // display_override вовсе (Safari/Firefox).
    display_override: ["window-controls-overlay", "standalone"],
    background_color: "#18181b",
    theme_color: "#18181b",
    icons: [
      {
        src: "/icon-library/pwa/icon-192.png",
        sizes: "192x192",
        type: "image/png",
      },
      {
        src: "/icon-library/pwa/icon-512.png",
        sizes: "512x512",
        type: "image/png",
      },
      // Несколько размеров maskable-иконки, не только 512 — некоторые
      // Android-лаунчеры (замечено на Samsung: "что-то добавляется, но
      // криво") берут ближайший подходящий размер для иконки на главном
      // экране, а не масштабируют один большой файл. Размеры 180/192/512
      // подсмотрены у Progressify (WP-плагин с рабочей PWA-установкой на
      // тех же устройствах, см. Progressify/includes/.../PwaAssets.php —
      // processMaskableIconVariants() генерирует ровно эти три размера).
      {
        src: "/icon-library/pwa/icon-180-maskable.png",
        sizes: "180x180",
        type: "image/png",
        purpose: "maskable",
      },
      {
        src: "/icon-library/pwa/icon-192-maskable.png",
        sizes: "192x192",
        type: "image/png",
        purpose: "maskable",
      },
      {
        src: "/icon-library/pwa/icon-512-maskable.png",
        sizes: "512x512",
        type: "image/png",
        purpose: "maskable",
      },
    ],
  };
}
