-- Безлимитная длительность варианта тарифа (запрос пользователя 2026-09-01):
-- «За вход» с фиксированной ценой, но без ограничения времени — сеанс идёт,
-- пока оператор не остановит его сам.
--
-- NULL означает «без ограничения». Ноль под это НЕ занимаем: им уже помечены
-- именованные ставки тарифа «По факту», где длительности нет по смыслу
-- (плейсхолдер пишут оба роута тарифов). Иначе все существующие ставки
-- «Будни»/«Выходные» молча стали бы бесконечными.
--
-- Снятие NOT NULL существующие строки не трогает: у всех вариантов «За вход»
-- сейчас положительная длительность, у ставок «По факту» — ноль. Значение
-- NULL появляется только у вариантов, созданных после этой правки.
ALTER TABLE "TariffOption" ALTER COLUMN "durationMinutes" DROP NOT NULL;
