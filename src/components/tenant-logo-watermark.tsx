// Логотип тенанта едва проглядывающим водяным знаком в углу (запрос
// пользователя 2026-07-27) — только PWA Сотрудника (operator-branding-chrome.tsx);
// в кабинете Владельца убран целиком (запрос того же дня, после нескольких
// раундов правок z-index/маски/непрозрачности). Нет логотипа — ничего не
// рендерим.
//
// z-index: -1 — реальный баг, найден пользователем 2026-07-27 дважды, в
// разные стороны, тот же цикл, что у BgEffectLayer (bg-effects/index.tsx):
// отрицательный z-index прятался за bg-surface-0 (полотно страницы,
// непрозрачно на устройстве без выбранного "Фон приложения" — временно
// переводили на z-index: 1), но тогда логотип стал всплывать ПОВЕРХ
// карточек/плашек без собственного стекинг-контекста. "Под всеми
// плашками" (запрос пользователя того же дня) важнее, чем "виден при
// любом Фон приложения" — тот же компромисс, что уже принят для эффектов.
//
// mix-blend-mode — реальная жалоба пользователя 2026-07-27: "белый фон у
// логотипов вообще не должен быть виден". Многие загруженные логотипы —
// JPG без альфа-канала (JPG физически не поддерживает прозрачность), у
// них есть настоящая непрозрачная заливка вокруг знака — ни маска, ни
// opacity этого не лечат (маска/opacity одинаково гасят ВЕСЬ пиксель,
// включая сам знак, не только фон вокруг него).
// mix-blend-mode: multiply — стандартный CSS-приём "убрать белый фон без
// альфа-канала": белый — нейтральный элемент умножения (white × X = X),
// поэтому белая заливка становится визуально неотличима от того, что под
// ней, а более тёмные пиксели (сам знак) остаются видны. На тёмной теме
// раньше тем же способом инвертировали цвета логотипа (белый фон -> чёрный
// + screen), но пользователь отклонил это решение 2026-07-29 ("не надо
// делать инверсию логотипа на тёмной теме") — собственные цвета бренда
// важнее идеального удаления фона; на dark просто mix-blend-normal
// (родные цвета логотипа как есть, без попытки спрятать белую подложку).
//
// Маска — линейная от угла, не радиальная (радиальная с default
// farthest-corner растягивала видимое "ядро" почти на весь экран вместо
// мягкого затухания у самого угла). Видимая (сплошная) зона — 80% от угла,
// гаснет только на последних 20% пути (запрос пользователя 2026-07-27:
// "сейчас видимы 20%, а надо наоборот").
const CORNER_FADE_MASK = "linear-gradient(to bottom left, black 0%, black 80%, transparent 100%)";

// data-tenant-logo-watermark — не стилевой хук, только маркер для
// globals.css (html:has([data-tenant-logo-watermark])) — тот же
// непрозрачный bg-surface-0, что гасил BgEffectLayer (см. комментарий там),
// точно так же гасил и этот логотип на любой странице без выбранного
// отдельно "Фон приложения" (реальный баг, найден пользователем 2026-07-28:
// "на Safari логотип всё равно где-то далеко" — на самом деле не "далеко",
// а почти невидим на сплошном сером, отчего расположение читалось как
// случайное/оторванное от остального интерфейса).
export function TenantLogoWatermark({ logoUrl }: { logoUrl: string | null }) {
  if (!logoUrl) return null;
  return (
    // eslint-disable-next-line @next/next/no-img-element
    <img
      src={logoUrl}
      alt=""
      aria-hidden
      data-tenant-logo-watermark
      // top-12 — верхняя панель (Сменить сотрудника/переключатель темы) —
      // строка в нормальном потоке, p-2 (8px) + h-7 переключателя (28px) +
      // 8px ≈ 44px реальной высоты; top-9 (36px, прежнее значение) на самом
      // деле садился ВНУТРЬ этой строки на 8px, не под ней — реальный баг,
      // найден пользователем 2026-07-28 живым скриншотом (широкий
      // landscape-логотип "kereg" наезжал на переключатель) — top-12 (48px)
      // даёт настоящий зазор ниже строки, а не в обрез. top-0 садил лого
      // вровень с переключателем совсем (более ранняя правка того же дня).
      // w-[20vw] — ширина ровно 20% ширины экрана (запрос пользователя
      // 2026-07-28), не фиксированный w-48. Высота — max-h, НЕ aspect-ratio
      // (реальный баг, найден тем же днём: "сейчас логотип очень
      // маленький" — aspect-2/1 задавал коробку 2:1, и логотип, у которого
      // натуральные пропорции ближе к квадрату/уже, чем 2:1, оказывался
      // HEIGHT-constrained внутри неё — object-contain сжимал его ПО
      // ШИРИНЕ меньше полных 20vw, визуально мельче, чем должен быть).
      // Высота auto (не задаётся) — логотип рендерится на всю ширину vw с
      // натуральными пропорциями; max-h — потолок, включается только для
      // непропорционально высоких/квадратных логотипов, чтобы не наезжать
      // на переключатель темы (top-12 — строка переключателя занимает
      // ~44px, top-9, прежнее значение, садился внутрь неё на 8px). w-28vw/
      // max-h-72 (запрос пользователя 2026-07-28, ещё один раунд: "и в
      // локальном браузере маленький" — было 20vw/max-h-56) — потолок
      // поднят пропорционально ширине, чтобы не стать новым узким местом.
      className="pointer-events-none fixed right-0 top-12 max-h-72 w-[28vw] object-contain opacity-40 mix-blend-multiply dark:mix-blend-normal"
      style={{
        zIndex: -1,
        // translateZ(0) — тот же баг и то же лекарство, что у BgEffectLayer
        // (bg-effects/index.tsx, тем же днём: "чтобы увидеть эффект надо
        // потянуть") — position:fixed с отрицательным z-index иногда не
        // промотируется в composited layer сразу на WebKit/старом Chromium.
        transform: "translateZ(0)",
        objectPosition: "top right",
        maskImage: CORNER_FADE_MASK,
        WebkitMaskImage: CORNER_FADE_MASK,
      }}
    />
  );
}
