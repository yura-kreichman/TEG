import { NextResponse } from "next/server";

// Текущая версия сборки на сервере (запрос владельца 2026-08-13).
//
// Клиент (components/version-watcher.tsx) сравнивает её с той, с которой сам
// загрузился, и перезагружает страницу при расхождении. Нужно потому, что
// планшет на точке держит приложение открытым сутками: после ночного деплоя
// страница живёт со ссылками на чанки, которых на сервере уже нет.
//
// Значение — то же самое, что Next кладёт в data-dpl-id на <html>
// (deploymentId в next.config.ts), берётся из окружения сборки. Не задано
// (локальная разработка) — отдаём null, и наблюдатель на клиенте выключается
// сам: в dev пересборка и так перезагружает страницу.
//
// no-store обязателен: закэшированный ответ означал бы, что клиент вечно
// видит старую версию и никогда не перезагрузится — то есть ровно та
// проблема, которую этот роут и решает.
export const dynamic = "force-dynamic";

export async function GET() {
  return NextResponse.json(
    { id: process.env.NEXT_DEPLOYMENT_ID ?? null },
    { headers: { "Cache-Control": "no-store" } }
  );
}
