import { hash, verify } from "@node-rs/bcrypt";

// Единственное место, где проект знает, чем считается bcrypt (аудит
// производительности 2026-08-13). Раньше три файла независимо импортировали
// bcryptjs — auth.ts (пароль и ПИН владельца), operator-auth.ts (ПИН
// сотрудника), login-lockout.ts (выравнивание времени ответа); менять
// реализацию в одном и забыть в другом означало бы разъехавшийся тайминг,
// то есть возвращённый оракул перечисления.
//
// Почему ушли с bcryptjs. Он на чистом JS, и его «асинхронный» compare на
// самом деле считает В ГЛАВНОМ ПОТОКЕ, нарезая работу через setImmediate.
// Замерено на этой машине (6 ядер), cost=12:
//
//   одно сравнение:            bcryptjs 281 мс   @node-rs 232 мс
//   8 входов одновременно:     bcryptjs 2272 мс  @node-rs  527 мс
//   задержка цикла событий:    bcryptjs 353 мс   @node-rs    1 мс
//
// Важна не первая строка, а третья. 353 мс задержки означают, что пока
// ОДИН человек вводит пароль, весь сервер стоит: не отвечают опросы PWA
// других точек, не открываются страницы, не проходят вебхуки. Приложение
// живёт одним процессом Node, и вход смены в 9:00 на нескольких точках
// складывался бы в секунды простоя для всех. @node-rs/bcrypt — нативный
// (Rust), считает в пуле потоков libuv: главный поток свободен, а
// параллельные проверки реально идут параллельно по ядрам.
//
// Формат хешей не меняется: это тот же bcrypt ($2b$). Проверено обоими
// направлениями — новая библиотека принимает хеши, выданные bcryptjs, и
// наоборот, поэтому ни перехеширования, ни сброса паролей не нужно, и
// откат на прежнюю библиотеку остаётся возможным.
//
// Готовые бинарники есть и под alpine (linux-x64-musl, образ прода), и под
// Windows — node-gyp с python и g++ в Dockerfile добавлять не пришлось.
const ROUNDS = 12;

export function hashSecret(plain: string): Promise<string> {
  return hash(plain, ROUNDS);
}

export function verifySecret(plain: string, hashed: string): Promise<boolean> {
  return verify(plain, hashed);
}
