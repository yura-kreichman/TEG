-- Индекс отбора кандидата при входе Сотрудника по ПИНу (аудит 2026-08-13).
--
-- До него findOperatorByPin (src/lib/operator-auth.ts) грузил ВСЕХ сотрудников
-- тенанта и делал bcrypt.compare на каждого. Замерено, а не оценено: bcryptjs
-- на cost=12 — ~285 мс на одно сравнение, то есть 14 с CPU на один неверный
-- ПИН при 50 сотрудниках, при разрешённых 20 неверных ПИНах за 5 минут на
-- устройство. Одно устройство точки могло заказать почти пять минут чистого
-- CPU за пять минут.
--
-- Колонка "pin" (ПИН открытым текстом) существует с 2026-07-14 — Владелец
-- может посмотреть ПИН сотрудника повторно. Индекс не добавляет к этому
-- ничего нового: значение уже лежало в строке. Проверка доступа осталась на
-- "pinHash" — "pin" используется только как ключ отбора.
--
-- Строки со старым NULL в "pin" индексом не находятся: восстановить значение
-- нечем (из bcrypt-хеша ПИН не достаётся by design), поэтому для них остаётся
-- прежний перебор, и колонка дозаполняется приложением на первом успешном
-- входе такого сотрудника. Разового backfill-скрипта здесь быть не может.
CREATE INDEX "Operator_tenantId_pin_idx" ON "Operator"("tenantId", "pin");
