import { headers } from "next/headers";
import { NONCE_HEADER } from "@/lib/csp";

/**
 * CSP-nonce текущего запроса — для НАШИХ собственных <script>-тегов. Скриптам,
 * которые вставляет сам Next (бутстрап, чанки страницы), nonce он проставляет
 * сам, читая CSP из заголовков запроса; всё, что мы пишем в разметке руками,
 * он не видит и не трогает.
 *
 * Пустая строка, если заголовка нет — например при рендере вне запроса. Пустой
 * nonce не совпадёт ни с чем в политике, то есть скрипт просто не выполнится;
 * это правильнее, чем отдать разметку, которая молча обходит CSP.
 */
export async function getNonce(): Promise<string> {
  return (await headers()).get(NONCE_HEADER) ?? "";
}
