-- Снапшот учёта остатка на момент продажи (генеральная проверка финансов
-- 2026-09-02). Аннулирование возвращало штуки по текущему Goods.trackStock:
-- у товара, которому учёт включили уже после продажи, возврат прибавлял то,
-- что никогда не списывалось. Nullable без default: NULL означает «продажа
-- старше этой миграции», и для неё сохраняется прежнее чтение текущего флага.
ALTER TABLE "GoodsSale"
  ADD COLUMN "stockTracked" BOOLEAN;

-- То же самое для позиций отложенного заказа: остаток списывается при
-- откладывании и возвращается при отмене — по флагу, который мог измениться
-- между этими двумя моментами.
ALTER TABLE "GoodsHeldOrderLine"
  ADD COLUMN "stockTracked" BOOLEAN;
