import { NextResponse } from "next/server";
import { currentVersion } from "@/lib/changelog";

// Текущая версия сборки на сервере (запрос владельца 2026-08-13).
//
// Поле id — идентификатор деплоя. Клиент (components/version-watcher.tsx)
// сравнивает его с тем, с которым сам загрузился, и перезагружает страницу при
// расхождении. Нужно потому, что планшет на точке держит приложение открытым
// сутками: после ночного деплоя страница живёт со ссылками на чанки, которых
// на сервере уже нет. Значение — то же самое, что Next кладёт в data-dpl-id на
// <html> (deploymentId в next.config.ts), берётся из окружения сборки. Не
// задано (локальная разработка) — отдаём null, и наблюдатель на клиенте
// выключается сам: в dev пересборка и так перезагружает страницу.
//
// Поле version — человеческая версия из истории изменений (changelog/README.md).
// Её показывает подвал rentos365.app рядом со строкой доступности; меняется
// раз в день максимум, в отличие от id, который меняется на каждом деплое.
// Живёт здесь, а не в отдельном роуте: подвалу нужен один запрос, а не два.
//
// no-store обязателен: закэшированный ответ означал бы, что клиент вечно видит
// старую версию и никогда не перезагрузится — то есть ровно та проблема,
// которую этот роут и решает.
export const dynamic = "force-dynamic";

export async function GET() {
  return NextResponse.json(
    { id: process.env.NEXT_DEPLOYMENT_ID ?? null, version: currentVersion },
    { headers: { "Cache-Control": "no-store" } }
  );
}
