// Логотип тенанта едва проглядывающим водяным знаком в углу (запрос
// пользователя 2026-07-27) — общий для кабинета Владельца и PWA Сотрудника
// (см. owner-shell.tsx/operator-branding-chrome.tsx), каждый сам решает,
// откуда взять logoUrl. Нет логотипа — ничего не рендерим (запрос того же
// дня).
//
// z-index: 1, не отрицательный — настоящая причина "логотип реально не
// видно" (запрос пользователя 2026-07-27, живые фото): bg-surface-0
// (полотно каждой страницы) полупрозрачен ТОЛЬКО когда на ЭТОМ устройстве
// в Настройки → Внешний вид → "Фон приложения" выбран не "Без фона" — это
// cookie конкретного устройства/браузера (globals.css,
// html:has(.app-bg[data-bg-style))), никак не связанная с новым
// тенант-эффектом logoUrl/bgEffect. На устройстве с "Без фона" полотно
// полностью непрозрачно и глушит любой отрицательный z-index — логотип
// молча пропадал бы независимо от собственных настроек, только из-за
// чужого, не связанного тумблера. z-index: 1 кладёт его НАД полотном
// страницы (но карточки контента всё равно непрозрачны и перекрывают его
// там, где реально накладываются) — гарантированно виден при любом "Фон
// приложения".
//
// dark:invert — запрос пользователя 2026-07-27, несколько заходов: сначала
// useTheme()+JS-фильтр (ценой hydration mismatch, реальный баг "ошибка на
// странице"), потом grayscale+dark:invert (убрали grayscale по запросу того
// же дня — известный компромисс: оригинальные цвета логотипа на светлой
// теме могут оказаться слишком светлыми/ненасыщенными при 20% и почти не
// читаться, это уже видели живьём при первой попытке без grayscale).
// Чистым CSS-классом через next-themes attribute="class" на <html>, без JS
// и без риска рассинхрона сервер/клиент — тот же приём, что dark: у
// остальных утилит в owner-shell.tsx.
//
// Маска — линейная от угла, не радиальная (реальный баг, тот же день:
// радиальная с default farthest-corner растягивала видимое "ядро"
// водяного знака почти на весь экран вместо мягкого затухания у самого
// угла). transparent 65% гасило слишком рано — с нижнего левого края почти
// ничего не оставалось (реальный баг, тот же день, живой скриншот) —
// держим полную видимость дольше (0-40%), гасим только у самого края (90%).
const CORNER_FADE_MASK = "linear-gradient(to bottom left, black 0%, black 40%, transparent 90%)";

export function TenantLogoWatermark({ logoUrl }: { logoUrl: string | null }) {
  if (!logoUrl) return null;
  return (
    // eslint-disable-next-line @next/next/no-img-element
    <img
      src={logoUrl}
      alt=""
      aria-hidden
      className="pointer-events-none fixed right-0 top-0 w-40 opacity-40 dark:invert"
      style={{
        zIndex: 1,
        maskImage: CORNER_FADE_MASK,
        WebkitMaskImage: CORNER_FADE_MASK,
      }}
    />
  );
}
