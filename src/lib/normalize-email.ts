import { prisma } from "@/lib/prisma";

// Приведение email к каноническому виду (аудит 2026-08-13).
//
// До этого email не нормализовался НИГДЕ: ни при регистрации, ни при входе, ни
// в «Забыли пароль», ни при привязке покупок FluentCart. Колонка User.email —
// @unique, а уникальность в Postgres регистрозависима, поэтому:
//
//  * "Ivan@mail.ru" и "ivan@mail.ru" — два разных аккаунта на один настоящий
//    почтовый ящик, и проверка «пользователь с таким email уже существует»
//    их не ловила: findUnique искал точное совпадение строки;
//  * владелец, набравший свой адрес с заглавной (телефон подставляет её сам),
//    не мог войти и получал «Неверные учётные данные» на верном пароле;
//  * покупка на сайте привязывалась по email — при другом регистре она
//    оставалась висеть непривязанной.
//
// Хвостовая часть адреса (домен) регистронезависима по стандарту всегда;
// локальная часть формально может быть регистрозависимой, но ни один живой
// почтовый провайдер этим не пользуется, а цена такой строгости здесь —
// как раз дубли аккаунтов на один ящик.
export function normalizeEmail(raw: string): string {
  return raw.trim().toLowerCase();
}

// Поиск пользователя без учёта регистра — а не findUnique по нормализованной
// строке. Разница важна для УЖЕ заведённых записей: в базе могли осесть адреса
// с заглавными буквами (их писали до этой правки), и findUnique("ivan@…") их
// просто не нашёл бы, то есть владелец так и остался бы заперт снаружи.
// Разовой миграции «привести все email к нижнему регистру» здесь сознательно
// нет: если в базе уже лежат два адреса, различающиеся только регистром, такая
// миграция упала бы на @unique посреди деплоя.
//
// orderBy — на случай тех самых двух записей: выбор должен быть
// детерминированным (самая старая), а не «какую вернёт планировщик».
export async function findUserByEmail(rawEmail: string) {
  return prisma.user.findFirst({
    where: { email: { equals: normalizeEmail(rawEmail), mode: "insensitive" } },
    orderBy: { createdAt: "asc" },
  });
}
