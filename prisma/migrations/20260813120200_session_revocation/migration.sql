-- Отзыв ранее выданных сессий при смене пароля (аудит 2026-08-13).
--
-- Подпись сессионного токена зависит только от userId, поэтому выпуск нового
-- токена никогда не обесценивал старый: смена или сброс пароля выдавали свежую
-- куку, а уже перехваченное значение работало до конца своего срока (до
-- недели). Токен теперь несёт время выдачи, а эта колонка — границу годности;
-- всё, что выдано раньше неё, не принимается. См. lib/session-revocation.ts.
--
-- NULL у существующих пользователей — «ничего не отзывалось», проверка для них
-- не срабатывает. Отдельно обесценивать текущие сессии здесь не нужно: формат
-- токена изменился в этом же релизе (три части → четыре), поэтому все ранее
-- выданные session/admin_session куки перестанут приниматься сами по себе, и
-- владельцы с админами один раз войдут заново.
ALTER TABLE "User" ADD COLUMN "sessionsValidFrom" TIMESTAMP(3);
