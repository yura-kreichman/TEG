import type { Locale } from "@/lib/locales";

// Публичная страница с ценами на основном сайте (docs/spec/06-super-admin.md)
// — там же оформляется покупка/смена пакета через FluentCart (тем же email,
// что и в RentOS, чтобы вебхук сам привязал новый пакет). Нет отдельного
// клиентского портала FluentCart на этом сайте (решение пользователя
// 2026-07-12) — "Управлять подпиской" и баннер неактивной подписки ведут
// именно сюда, не на портал. Адрес собирается pricingUrl() ниже: до
// 2026-08-10 это была одна константа, и владелец с любым языком интерфейса
// попадал на русскую страницу.
//
// Языков у сайта пять (TranslatePress: ru базовый без префикса, en/ua/it/ro),
// у RentOS — пятнадцать, поэтому остальные десять надо куда-то распределить.
// Правило (решение пользователя 2026-08-10): страны, где русский остаётся
// рабочим языком делового общения, — на русскую версию; те, где он не в
// ходу, — на английскую. Отсюда pl и tr — единственные исключения из
// "постсоветской" группы: Польша это ЕС, а Турция и вовсе не из этого круга.
// Украина и Молдова имеют собственные версии сайта и в группу не попадают.
//
// ВАЖНО: префикс украинского на сайте — "ua" (url-slugs в настройках
// TranslatePress), а код языка в RentOS — "uk". Их несовпадение уже стоило
// одной правки mu-плагина сайта, здесь оно тоже единственная неочевидная
// строка карты.
const SITE_LANG_PREFIX: Record<Locale, string> = {
  ru: "",
  en: "en/",
  uk: "ua/",
  it: "it/",
  ro: "ro/",
  be: "",
  kk: "",
  ky: "",
  tg: "",
  uz: "",
  hy: "",
  az: "",
  ka: "",
  pl: "en/",
  tr: "en/",
};

/**
 * Имя query-параметра с токеном кабинета (lib/billing-token.ts). Тем же именем
 * он лежит в мете заказа и в теле вебхука — одно слово на все три системы,
 * чтобы его можно было найти грепом и в приложении, и в mu-плагине сайта
 * (wp-content/mu-plugins/rentos-checkout-token.php).
 */
export const BILLING_TOKEN_PARAM = "rentos_tid";

/**
 * Страница цен на языке владельца ("Управлять подпиской", баннер неактивной
 * подписки). Путь везде остаётся английским `prices/`: слаги страниц у
 * TranslatePress переведены (`/ua/tsiny/`, `/it/prezzi/`, `/ro/preturi/`), но
 * он же сам делает 301 с непереведённого пути на переведённый — один лишний
 * редирект дешевле, чем зашитые в приложение слаги, которые молча сломаются
 * при первом же переименовании страницы на сайте.
 *
 * billingToken — подписанный идентификатор кабинета, чтобы оплата привязалась
 * именно к нему, а не к кабинету с совпавшим email (см. lib/billing-token.ts).
 * Необязателен: без него ссылка ведёт туда же, куда вела всегда, и покупка
 * по-прежнему находит кабинет по email. 301 на переведённый слаг query-строку
 * сохраняет — проверено на живом сайте 2026-08-10 для /ua/ и /it/.
 */
export function pricingUrl(locale: Locale, billingToken?: string | null): string {
  const base = `https://rentos365.app/${SITE_LANG_PREFIX[locale]}prices/`;
  return billingToken ? `${base}?${BILLING_TOKEN_PARAM}=${encodeURIComponent(billingToken)}` : base;
}

