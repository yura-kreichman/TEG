"use client";

import { useEffect } from "react";

// Как часто спрашивать сервер о версии. 30 секунд — это «сразу» на практике
// (владелец 2026-08-13: «как только деплой пришёл, пусть сразу
// перезагружается»), и при этом один крошечный запрос в полминуты на вкладку,
// то есть заметно реже, чем уже идущий опрос данных на экранах Сотрудника.
const CHECK_INTERVAL_MS = 30_000;

/**
 * Перезагружает страницу, как только на сервере появилась новая сборка.
 *
 * Зачем. Планшет точки держит приложение открытым сутками, а деплой идёт
 * ночью. К утру вкладка живёт со ссылками на чанки, которых на сервере уже
 * нет: переход по меню может просто не сработать, и выглядит это как
 * «приложение сломалось», а не как «нужно обновить».
 *
 * Next частично закрывает это сам (deploymentId в next.config.ts): при
 * расхождении версий он делает полную перезагрузку вместо клиентского
 * перехода. Но только В МОМЕНТ ПЕРЕХОДА — планшет, стоящий на одном экране,
 * так и останется на старом коде, пока его никто не тронет. Этот наблюдатель
 * закрывает именно тот случай.
 *
 * Перезагрузка БЕЗ предупреждения и без оглядки на занятость — прямое решение
 * владельца, дважды подтверждённое: «пусть перезагружается сразу, не обращая
 * внимание на занятость сотрудника». Баннер «доступно обновление» он отклонил
 * («какой смысл писать»). Риск здесь один — начатый мастер сдачи итогов
 * потеряет введённое; владелец про это знает и принял, потому что деплои
 * делает ночью, когда за планшетом никого нет.
 *
 * Своя версия приходит ПРОПСОМ из серверного layout, а не читается из
 * data-dpl-id на <html>. Next этот атрибут в разметку кладёт, но React при
 * гидратации его снимает: RootLayout рендерит <html> без него, и на клиенте
 * он пропадает (проверено — в DOM после гидратации атрибута нет). Пропс не
 * зависит от внутренностей фреймворка и переживёт обновление Next.
 *
 * Пусто (локальная разработка, идентификатор не задан) — наблюдатель молча
 * выключается: в dev пересборка и так перезагружает страницу.
 */
export function VersionWatcher({ version }: { version: string | null }) {
  useEffect(() => {
    const own = version;
    if (!own) return;

    let stopped = false;

    async function check() {
      if (stopped || document.visibilityState !== "visible") return;
      try {
        const res = await fetch("/api/version", { cache: "no-store" });
        if (!res.ok) return;
        const data = (await res.json()) as { id: string | null };
        if (!data.id || data.id === own) return;
        // Версия сменилась — уходим на свежую сборку. reload(), а не
        // router.refresh(): нужен именно новый документ со свежими адресами
        // чанков, клиентское обновление осталось бы на старом бандле.
        window.location.reload();
      } catch {
        // Сеть недоступна — это норма на точке, проверим в следующий раз.
      }
    }

    const interval = setInterval(check, CHECK_INTERVAL_MS);
    // Планшет разбудили или вернулись в приложение — проверяем не дожидаясь
    // тика: за ночь в фоне интервал мог не отработать ни разу.
    document.addEventListener("visibilitychange", check);

    return () => {
      stopped = true;
      clearInterval(interval);
      document.removeEventListener("visibilitychange", check);
    };
  }, [version]);

  return null;
}
